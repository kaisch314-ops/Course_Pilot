from playwright.sync_api import sync_playwright,expect
from uuid import uuid4
with sync_playwright() as p:
 b=p.chromium.launch(channel='msedge');page=b.new_page()
 page.goto('http://127.0.0.1:8765/')
 page.get_by_role('button',name='首次使用，创建账户').click()
 page.get_by_label('用户名',exact=True).fill('check_'+uuid4().hex[:10])
 page.get_by_label('密码',exact=True).fill(uuid4().hex)
 page.get_by_role('button',name='创建账户并登录').click()
 expect(page.get_by_role('heading',name='我的学期课表')).to_be_visible()
 page.get_by_role('button',name='打开选课咨询').click()
 page.get_by_label('咨询内容').fill('我想学数据分析')
 page.get_by_role('button',name='发送消息').click()
 expect(page.get_by_role('button',name='按这个安排更新课表')).to_be_visible()
 page.get_by_role('button',name='反馈选课与修读情况').click()
 page.get_by_label('目前情况').select_option('completed')
 page.get_by_label('每周课外投入（小时，可不填）').fill('8')
 page.get_by_role('button',name='保存反馈',exact=True).click()
 expect(page.get_by_text('已保存，谢谢你的反馈。你可以随时修改或撤回。')).to_be_visible()
 page.get_by_role('button',name='反馈选课与修读情况').click()
 page.get_by_role('button',name='撤回该课程反馈').click()
 expect(page.get_by_text('已撤回这门课的反馈')).to_be_visible()
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 page.screenshot(path='feedback-mobile.png')
 page.get_by_role('button',name='收起选课咨询').click()
 page.get_by_role('button',name='退出登录').click()
 expect(page.get_by_role('heading',name='开启你的学期规划')).to_be_visible()
 b.close()
print('PASS: register, login, original workbench, authenticated chat, logout')

